// handleCreateKey proxies POST /api/keys to Garage POST /v2/CreateKey.
func handleCreateKey(garageAdmin *GarageAdminClient) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		// The response carries the new secret: keep it out of caches.
		w.Header().Set("Cache-Control", "no-store")
		proxyGarageMutation(w, r, garageAdmin, "/v2/CreateKey", r.Body)
	}
}

// maxImportKeyBodyBytes bounds the POST /api/keys/import body.
const maxImportKeyBodyBytes = 4 << 10

// importKeyRequest is Garage's ImportKeyRequest (POST /v2/ImportKey).
type importKeyRequest struct {
	AccessKeyID     string  `json:"accessKeyId"`
	SecretAccessKey string  `json:"secretAccessKey"`
	Name            *string `json:"name"`
}

// validateImportKey mirrors the checks of Key::import in Garage v2.4.1
// (src/model/key_table.rs) so a malformed pair is rejected with a clear 400
// before it reaches Garage. It returns "" when the pair is acceptable.
//
//   - accessKeyId: at least 8 characters, ASCII alphanumerics and "-_."
//   - secretAccessKey: at least 16 characters, graphic ASCII (U+0021..U+007E)
//
// Keys generated by Garage itself ("GK" + 24 hex, 64 hex secret) pass.
func validateImportKey(req importKeyRequest) string {
	id, secret := req.AccessKeyID, req.SecretAccessKey
	if len(id) < 8 {
		return "accessKeyId must be at least 8 characters long"
	}
	for i := 0; i < len(id); i++ {
		c := id[i]
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-' || c == '_' || c == '.') {
			return "accessKeyId must contain only ASCII alphanumerics and '-', '_', '.'"
		}
	}
	if len(secret) < 16 {
		return "secretAccessKey must be at least 16 characters long"
	}
	for i := 0; i < len(secret); i++ {
		if c := secret[i]; c < 0x21 || c > 0x7e {
			return "secretAccessKey must contain only graphic ASCII characters (U+0021 to U+007E)"
		}
	}
	return ""
}

// handleImportKey proxies POST /api/keys/import to Garage POST /v2/ImportKey,
// which imports an existing access key / secret pair (migration from another
// cluster). The body is validated first (400 on a malformed pair). Garage
// v2.4.1 answers GetKeyInfoResponse without the secret (verified against a
// real instance). Non-2xx answers (e.g. 409 KeyAlreadyExists) are forwarded
// as-is.
func handleImportKey(garageAdmin *GarageAdminClient) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "no-store")
		data, ok := readRequestBody(w, r, maxImportKeyBodyBytes)
		if !ok {
			return
		}
		var req importKeyRequest
		if err := json.Unmarshal(data, &req); err != nil {
			writeJSONError(w, http.StatusBadRequest, "invalid JSON body")
			return
		}
		if msg := validateImportKey(req); msg != "" {
			writeJSONError(w, http.StatusBadRequest, msg)
			return
		}
		if req.Name != nil {
			if name := strings.TrimSpace(*req.Name); name == "" {
				// Let Garage apply its default name ("Imported key").
				req.Name = nil
			} else {
				req.Name = &name
			}
		}
		body, err := json.Marshal(req)
		if err != nil {
			writeJSONError(w, http.StatusInternalServerError, "cannot encode request")
			return
		}
		proxyGarageMutation(w, r, garageAdmin, "/v2/ImportKey", bytes.NewReader(body))
	}
}

// handleGetKey proxies GET /api/keys/{id} to Garage GET /v2/GetKeyInfo?id={id}.
// Passing ?showSecretKey=true asks Garage to include secretAccessKey in the
// response so operators can retrieve a key's secret from the UI.
func handleGetKey(garageAdmin *GarageAdminClient) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		id := chi.URLParam(r, "id")
		garagePath := "/v2/GetKeyInfo?id=" + url.QueryEscape(id)
		if r.URL.Query().Get("showSecretKey") == "true" {
			garagePath += "&showSecretKey=true"
			// The response carries the secret: keep it out of browser and proxy caches.
			w.Header().Set("Cache-Control", "no-store")
		}
		resp, err := garageAdmin.doRequest(r.Context(), http.MethodGet, garagePath, nil)
		if err != nil {
			slog.ErrorContext(r.Context(), "garage request failed", "path", garagePath, "error", err)
			http.Error(w, "Bad Gateway", http.StatusBadGateway)
			return
		}
		defer resp.Body.Close()

		ct := resp.Header.Get("Content-Type")
		if ct == "" {
			ct = "application/json"
		}
		w.Header().Set("Content-Type", ct)
		w.WriteHeader(resp.StatusCode)
		if _, err := io.Copy(w, resp.Body); err != nil {
			slog.ErrorContext(r.Context(), "failed to stream garage response", "path", garagePath, "error", err)
		}
	}
}

